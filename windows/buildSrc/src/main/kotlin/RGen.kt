import java.io.File
import javax.xml.parsers.DocumentBuilderFactory

/**
 * Jam for Windows: the Android app's R class (app.myspoti.engine.R) from its res/ folder, as the
 * Android build makes it: one Int id per resource. The ids are looked up at run time by name in
 * `rnames.txt` (type, name, id per line), next to the copied res/ (see androidx.compose.ui.res).
 */
object RGen {
    private val types = listOf("string", "plurals", "array", "drawable", "mipmap", "color", "raw", "font", "xml", "dimen", "integer", "bool", "style", "id", "layout", "anim")

    fun generate(res: File, src: File, out: File) {
        val names = types.associateWith { sortedSetOf<String>() }
        res.listFiles().orEmpty().forEach { dir ->
            val type = dir.name.substringBefore('-')
            when (type) {
                "values" -> dir.listFiles { f -> f.extension == "xml" }.orEmpty().forEach { valuesFile(it, names) }
                "drawable", "mipmap", "raw", "font", "xml", "layout", "anim" -> dir.listFiles().orEmpty().forEach { f ->
                    names.getValue(type) += f.name.substringBefore('.')
                    if (type == "layout") idsIn(f, names)
                }
            }
        }
        // Ids written as @+id/… in the code's own views, and the few R.id the Kotlin code names.
        src.walkTopDown().filter { it.extension == "kt" }.forEach { f ->
            Regex("\\bR\\.id\\.([A-Za-z0-9_]+)").findAll(f.readText()).forEach { names.getValue("id") += it.groupValues[1] }
        }
        val kt = File(out, "app/myspoti/engine").apply { mkdirs() }
        val sb = StringBuilder("// Generated by windows/buildSrc RGen from android/base/app/src/main/res. Do not edit.\n")
        sb.append("@file:Suppress(\"ObjectPropertyName\", \"ClassName\", \"unused\")\npackage app.myspoti.engine\n\nobject R {\n")
        val index = StringBuilder()
        types.forEachIndexed { t, type ->
            sb.append("    object $type {\n")
            names.getValue(type).forEachIndexed { i, n ->
                val id = 0x7f000000 or ((t + 1) shl 16) or i
                val name = n.replace('.', '_')
                sb.append("        const val `$name`: Int = $id\n")
                index.append(type).append(' ').append(name).append(' ').append(id).append('\n')
            }
            sb.append("    }\n")
        }
        sb.append("}\n")
        File(kt, "R.kt").writeText(sb.toString())
        File(out.parentFile, "rnames/res").apply { mkdirs() }.resolve("rnames.txt").writeText(index.toString())
    }

    private fun valuesFile(f: File, names: Map<String, MutableSet<String>>) {
        val doc = runCatching { DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(f) }.getOrNull() ?: return
        val nodes = doc.documentElement.childNodes
        for (i in 0 until nodes.length) {
            val n = nodes.item(i) as? org.w3c.dom.Element ?: continue
            val name = n.getAttribute("name").ifEmpty { continue }
            val type = when (n.tagName) {
                "string" -> "string"; "plurals" -> "plurals"
                "string-array", "array", "integer-array" -> "array"
                "color" -> "color"; "dimen" -> "dimen"; "integer" -> "integer"; "bool" -> "bool"
                "style" -> "style"; "item" -> n.getAttribute("type").ifEmpty { continue }
                else -> continue
            }
            names[type]?.add(name)
        }
    }

    private fun idsIn(f: File, names: Map<String, MutableSet<String>>) {
        Regex("@\\+id/([A-Za-z0-9_]+)").findAll(runCatching { f.readText() }.getOrDefault("")).forEach { names.getValue("id") += it.groupValues[1] }
    }
}
